"""guiro: 300 mm hollow guiro (scraped idiophone) in two glued halves + scraper stick.

Spec
- Tube OD 70 mm, 300 mm long, both ends closed, bore 60.6 mm. Ridges (sawtooth teeth, PITCH
  4.5 mm, 2.0 mm deep, 40 deg lower flank / steep upper flank, small flat lands) over a 110 deg sector on top along the full length
  except 20 mm at each end. Two finger holes (thumb + middle finger, 22 mm) underneath in half A,
  Helmholtz sound slot (8 mm wide, length solved) underneath in half B.
- Split at mid-length into two 150 mm halves printed upright (closed end on the bed): no
  ceilings anywhere, teeth flanks <= 40 deg from vertical. Half A carries a 12 mm sleeve spigot (slide fit into
  half B's bore) with a key rib at the bottom that fits a key slot in B -> ridges line up.
- Scraper: 170 x 12 x 6 mm stick, printed flat (load along the layers), tapered tip.
- Print layout (not in-use pose): both halves upright + stick on one plate. In use the axis is
  horizontal, ridges up, hand under the holes.

Acoustics (computed below; c = 343 m/s)
- Cavity Helmholtz: f = c/(2 pi) sqrt(A/(V L_eff)), L_eff = t + 1.7 r_eq, r_eq = sqrt(A/pi).
  Slot length is solved so f(slot only, finger holes plugged by the hand) = F_TARGET.
  Same with both finger holes open (adds their conductance) is reported too.
- Scrape rate: f_scrape = v / PITCH; scraping at v = F_TARGET * PITCH drives the cavity at its
  resonance (loudest, "boomy" stroke); slower strokes give a dry rattle.
- First longitudinal air mode (closed-closed) c / (2 L_in) for reference.

TUNING (regenerated by `python model.py`)
  item                          | target       | computed
  cavity volume                 |              | 842 cm3 (bore 60.6 x 294 mm minus spigot)
  Helmholtz, slot only          | 220 Hz (A3)  | slot 8.0 x 39.8 mm (L_eff 20.9 mm)
  Helmholtz, slot + finger holes|              | 404 Hz
  scrape rate v = 0.2/0.5/1 m/s | v / 4.5 mm   | 44 / 111 / 222 Hz
  scrape speed matching cavity  | 220 Hz       | 0.99 m/s
  longitudinal mode c/2L        |              | 583 Hz

Fine-tune after printing
- Deeper / boomier: tape over part of the slot (lower f); brighter: lengthen the slot with a file.
- Teeth are slightly asymmetric (40/52 deg) and mirrored between the halves (each half prints
  closed end down), so both stroke directions sound alike.
- Scrape with the stick's edge for sharp clicks, with its flat for a softer sound; vary speed.

Hardware: none. Glue: ABS cement (ABS dissolved in acetone) or 2-part epoxy for the joint.

Assembly: dry-fit A's spigot into B with the key rib in the key slot (ridges must line up); apply
ABS cement on the spigot and the A shoulder, push together, wipe excess, cure 24 h. Sand the seam
crest flat if a ridge step is felt.

Assumptions: slot neck depth = wall thickness at the bottom (4.5 mm); end correction 1.7 r (both
sides flanged); Helmholtz valid since the tube (300 mm) << wavelength at 220 Hz (1.56 m).
"""

import math

from build123d import *

from cadlib import *

META = dict(
    material="AzureFilm ABS PLUS @BBL H2C 0.4 nozzle",
    quality="standard",
    standing=False,
    loads=[],
    print_orientation=(0, 0, 0),  # laid out as printed: halves upright, stick flat
    supports="off",
    brim="auto",
    # WARN accepted: 3 bodies = half A, half B and the scraper, printed together.
)

C_SOUND = 343.0e3                 # mm/s
F_TARGET = 220.0                  # Helmholtz target (A3)

LENGTH = 300.0
HALF_L = LENGTH / 2
OD = 70.0
R_OUT = OD / 2
PITCH = 4.5
DEPTH = 2.0
LAND = 0.3                        # crest sits LAND outside the cylinder -> small flat land
FLANK = 40.0                      # down-facing tooth flank, deg from vertical (prints w/o support)
SECTOR = 110.0                    # degrees of ridged arc on top
END_PLAIN = 20.0
WALL_UNDER = 2.7                  # wall under the grooves
R_IN = R_OUT - DEPTH - WALL_UNDER
END_T = 3.0                       # closed end thickness
WALL = R_OUT - R_IN
SPIGOT_L = 12.0
SPIGOT_T = 2.5
SPIGOT_FIT = FIT["slide"]
KEY_W, KEY_H = 4.0, 1.4
FINGER_D = 22.0
FINGER_Z = (60.0, 105.0)          # along half A, from its closed end
SLOT_W = 8.0
SLOT_Z = 75.0                     # slot centre along half B
END_CORR = 1.7
STICK = (170.0, 12.0, 6.0)
GAP = 8.0


def _keff(area):
    r = math.sqrt(area / math.pi)
    return area / (WALL + END_CORR * r)


def volume():
    v = math.pi * R_IN**2 * (LENGTH - 2 * END_T)
    v -= math.pi * (R_IN**2 - (R_IN - SPIGOT_T) ** 2) * SPIGOT_L
    return v


def slot_area(w, l):
    return w * (l - w) + w * w / 2   # rectangle + two 90 deg pointed ends


def solve_slot():
    k_need = volume() * (2 * math.pi * F_TARGET / C_SOUND) ** 2
    lo, hi = SLOT_W + 0.1, 200.0
    for _ in range(60):
        m = (lo + hi) / 2
        if _keff(slot_area(SLOT_W, m)) < k_need:
            lo = m
        else:
            hi = m
    return (lo + hi) / 2


SLOT_L = solve_slot()


def helmholtz(k):
    return C_SOUND / (2 * math.pi) * math.sqrt(k / volume())


def tuning_table():
    k_slot = _keff(slot_area(SLOT_W, SLOT_L))
    k_all = k_slot + 2 * _keff(math.pi * FINGER_D**2 / 4)
    rows = [f"V {volume() / 1000:.0f} cm3, slot {SLOT_W} x {SLOT_L:.1f} mm -> {helmholtz(k_slot):.1f} Hz",
            f"slot + finger holes open: {helmholtz(k_all):.0f} Hz",
            "scrape " + " / ".join(f"{v} m/s {v * 1000 / PITCH:.0f} Hz" for v in (0.2, 0.5, 1.0)),
            f"matching speed {F_TARGET * PITCH / 1000:.2f} m/s, longitudinal {C_SOUND / 2 / (LENGTH - 2 * END_T):.0f} Hz"]
    return "\n".join(rows)


def _ridge_cutter():
    """Zig-zag teeth profile revolved over the top sector; crest phase fixed at the joint z=HALF_L."""
    pts = [(R_OUT + 3, HALF_L + 1), (R_OUT + LAND, HALF_L + 1)]
    k = 0
    while HALF_L - (k + 1) * PITCH >= END_PLAIN:
        z = HALF_L - k * PITCH
        run = (DEPTH + LAND) / math.tan(math.radians(FLANK))   # long down-facing flank
        pts += [(R_OUT + LAND, z), (R_OUT - DEPTH, z - run)]
        k += 1
    pts += [(R_OUT + LAND, HALF_L - k * PITCH), (R_OUT + 3, HALF_L - k * PITCH)]
    cut = revolve(Plane.XZ * Polygon(*pts, align=None), Axis.Z, SECTOR)
    return Rot(0, 0, 90 - SECTOR / 2) * cut     # centre the sector on +Y (in-use "top")


def _shell(top_extra=0.0):
    tube = Cylinder(R_OUT, HALF_L, align=(Align.CENTER, Align.CENTER, Align.MIN))
    tube = chamfer(tube.edges().group_by(Axis.Z)[0], 2.0)
    bore = Pos(0, 0, END_T) * Cylinder(R_IN, HALF_L, align=(Align.CENTER, Align.CENTER, Align.MIN))
    return tube - bore - _ridge_cutter()


def _hole_y(d, z, sign=-1):
    return Pos(0, sign * (R_IN + WALL / 2), z) * teardrop_hole(d, WALL + 6, along="Y")


def half_a():
    """Closed end down; open end carries the sleeve spigot (collar merged into the wall)."""
    part = _shell()
    ro = R_IN - SPIGOT_FIT
    ri = ro - SPIGOT_T
    z_c = HALF_L - 2 - (R_IN - ri)                     # 45 deg inner transition start
    collar = Pos(0, 0, z_c) * Cylinder(R_IN + 0.5, HALF_L - z_c, align=(Align.CENTER, Align.CENTER, Align.MIN))
    sleeve = Pos(0, 0, HALF_L - 0.5) * Cylinder(ro, SPIGOT_L + 0.5, align=(Align.CENTER, Align.CENTER, Align.MIN))
    y0, y1 = ro - 0.5, ro + KEY_H
    key = Pos(0, -(y0 + y1) / 2, HALF_L + (SPIGOT_L - 2) / 2) * Box(KEY_W, y1 - y0, SPIGOT_L - 2)
    inner = Pos(0, 0, z_c - 0.01) * Cone(R_IN + 0.01, ri, R_IN - ri + 0.01, align=(Align.CENTER, Align.CENTER, Align.MIN))
    inner += Pos(0, 0, HALF_L - 2) * Cylinder(ri, SPIGOT_L + 3, align=(Align.CENTER, Align.CENTER, Align.MIN))
    part = part + collar + sleeve + key - inner
    for z in FINGER_Z:
        part -= _hole_y(FINGER_D, z)
    return part


def half_b():
    """Closed end down; open end is the socket (its own bore) with a key slot at the bottom (-Y)."""
    part = _shell()
    y0, y1 = R_IN - 0.5, R_IN + KEY_H + 0.3
    z0 = HALF_L - SPIGOT_L - 1
    part -= Pos(0, -(y0 + y1) / 2, (z0 + HALF_L + 1) / 2) * Box(KEY_W + 0.6, y1 - y0, HALF_L + 1 - z0)
    w, l = SLOT_W, SLOT_L
    slot = Polygon((0, -l / 2), (w / 2, -l / 2 + w / 2), (w / 2, l / 2 - w / 2), (0, l / 2),
                   (-w / 2, l / 2 - w / 2), (-w / 2, -l / 2 + w / 2), align=None)
    cutter = extrude(Plane.XZ * slot, WALL + 6, both=True)   # normal along Y, local y = +Z
    part -= Pos(0, -(R_IN + WALL / 2), SLOT_Z) * cutter
    return part


def stick():
    l, w, t = STICK
    s = Box(l, w, t, align=(Align.CENTER, Align.CENTER, Align.MIN))
    s = chamfer(s.edges().group_by(Axis.Z)[-1], 1.0)
    s = chamfer(s.edges().group_by(Axis.Z)[0], 0.4)
    tip = Pos(l / 2, 0, 0) * Rot(0, 0, 45) * Box(w, w, 3 * t)    # pointed tip
    return s - tip


def build():
    dx = R_OUT + GAP / 2
    a = Pos(-dx, R_OUT + 2, 0) * half_a()
    b = Pos(dx, R_OUT + 2, 0) * half_b()
    s = Pos(0, -STICK[1] / 2 - 4, 0) * stick()
    return [a, b, s]


if __name__ == "__main__":
    print(tuning_table())
