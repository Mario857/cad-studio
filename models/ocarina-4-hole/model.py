"""ocarina-4-hole: English-pendant 4-hole ocarina in C (C5..C6), two glued halves, lanyard hole.

Spec
- Helmholtz resonator tuned to C5 (523.25 Hz) with all holes closed; the window (sound hole at
  the labium) is the neck. One octave C5..C6 (C major) from the 16 English-pendant combinations
  of 4 finger holes (2 per hand, front face). Mouthpiece on top, blown downwards, held upright.
- Chamber: elliptic double cone (sides steeper than 45 deg so every inner ceiling prints without
  support), front cut flat at Y_F (flat front wall carries window, labium and finger holes).
- Split horizontally at z = 0 (seam). The upper half contains the whole fipple: windway runs
  vertically (walls vertical in print orientation, like a whistle head printed upright), window
  and 0.5 mm labium edge with an 18 deg ramp. Both halves print SEAM-DOWN (lower half flipped),
  so the seam faces are flat on the bed and glue flat; 3 dowel pins align them.
- Lanyard: two vertical 3 mm holes through the seam rim at the left and right ends.

Acoustics (computed below; c = 343 m/s, 20 C)
- Helmholtz: f = c/(2 pi) sqrt(K/V), conductance K = A / L_eff, L_eff = t + 1.7 r (r = sqrt(A/pi),
  both ends flanged). Window: K_w; all closed f = C5 -> V = K_w c^2 / (2 pi f)^2.
- Open holes add conductance in parallel: f_n / f_C5 = sqrt(1 + sum(k_i)), k_i = K_i / K_w.
  The 4 conductances k_i are fitted (minimax, cents) to the C-major scale for the fingering
  assignment FINGERING; each k_i -> hole diameter by solving pi r^2 = k_i K_w (t + 1.7 r).
- Chamber size is solved from V (analytic integral of the cut double cone).

TUNING (regenerated by `python model.py`)
  note | target Hz | computed
  C5   |  523.25   | chamber 48.0 cm3, window 8.0 x 5.0 mm (K_w 4.41 mm), Rx 33.7 Ry 20.2 H 37.8
  D5   |  587.33   | RM open (k .243 -> RM d 2.7)     (-12 c)
  E5   |  659.26   | RI open (k .565 -> RI d 4.7)     (-12 c)
  F5   |  698.46   | RI+RM                            (+12 c)
  G5   |  783.99   | RI+RM+LM (k .410 -> LM d 3.8)    (-11 c)
  A5   |  880.00   | LI open (k 1.800 -> LI d 11.3)   (-9 c)
  B5   |  987.77   | LI+RI+RM                         (+11 c)
  C6   | 1046.50   | all open                         (+4 c)
  (+-12 c is the best any 4-conductance set can do for this fingering; corrected by breath.)
  Hole diameters above are acoustic; they print HOLE_UNDERSIZE (0.3 mm) smaller for reaming.

Fingering chart (seen from the player: front face away from you; x = closed, o = open)
       LI LM | RI RM          LI = left index (upper left), LM = left middle (lower left)
  C5   x  x  | x  x           RI = right index (upper right), RM = right middle (lower right)
  D5   x  x  | x  o           thumbs support the back; blow gently - Helmholtz pitch rises
  E5   x  x  | o  x           ~ +30..50 c with harder breath, so use breath for the last cents.
  F5   x  x  | o  o
  G5   x  o  | o  o
  A5   o  x  | x  x
  B5   o  x  | o  o
  C6   o  o  | o  o

Fine-tune after printing (glue first! the seam must be airtight)
1. C5 (all closed): if flat, sand the window 0.2 mm longer toward the windway (raises K_w);
   if sharp, narrow the window sides with thin tape (lowers K_w). Expect +-25 c print tolerance.
2. Holes are printed 0.3 mm undersize: ream each with a drill bit by hand in 0.2 mm steps, in order
   D (RM), E (RI), G (LM), A (LI), checking every fingering with a tuner. Bigger hole = sharper.
3. Weak/airy: clear the windway with a card and straighten the labium edge with a sharp blade.

Hardware: 3x steel dowel pin 2 x 8 mm (or 1.75 mm filament pieces, 8 mm); ABS cement (ABS
dissolved in acetone) or medium CA glue; optional cord 2-3 mm, 600 mm, for the lanyard.

Assembly: dry-fit the halves on the pins; apply a thin bead of ABS cement on the lower seam face
(keep 2 mm away from the inner edge so no glue runs into the chamber); press, clamp 1 h, cure 24 h.
Deburr the windway exit and holes, then tune as above. Thread the cord through both rim holes.

Assumptions: A4 = 440 Hz, 20 C; flanged-neck end correction 1.7 r for window and holes; window
treated as a neck of depth = WALL; small volume changes from the beak/labium ignored (tuned by
reaming). Parts laid seam-down side by side on one plate (not in-use orientation; in use the upper
half sits on the lower one with the mouthpiece up). ABS is not food-safe — personal use, rinse
after playing.
"""

import math

from build123d import *

from cadlib import *

META = dict(
    material="AzureFilm ABS PLUS @BBL H2C 0.4 nozzle",
    quality="fine",               # windway + labium
    standing=False,
    loads=[],
    print_orientation=(0, 0, 0),  # parts are already laid seam-down; windway vertical
    supports="off",               # all inner ceilings are steeper than 45 deg
    brim="auto",
    # WARN accepted: 2 bodies = the two halves, printed together.
)

# --- Musical targets -----------------------------------------------------------------------
C_SOUND = 343.0e3                 # mm/s
A4 = 440.0
NOTES = ["C5", "D5", "E5", "F5", "G5", "A5", "B5", "C6"]
SEMIS = [3, 5, 7, 8, 10, 12, 14, 15]   # from A4
HOLES = ["RM", "LM", "LI", "RI"]       # hole ids, small .. large-ish
# open holes per note (English pendant style assignment, D..C6)
FINGERING = [(), ("RM",), ("RI",), ("RI", "RM"), ("RI", "RM", "LM"), ("LI",), ("LI", "RI", "RM"),
             ("LI", "LM", "RI", "RM")]
END_CORR = 1.7                    # L_eff = t + END_CORR * r
HOLE_UNDERSIZE = 0.3              # print holes smaller, ream to pitch

# --- Geometry -------------------------------------------------------------------------------
WALL = 3.0
RIM = 5.0                         # horizontal wall at the seam (room for dowel pins)
ASPECT = 0.6                      # chamber depth (Y) / width (X)
SLOPE = 1.12                      # chamber cone height / radius (> 1 = steeper than 45 deg)
FLAT = 0.5                        # front flat at Y_F = FLAT * Ry
WINDWAY_H = 1.1
WINDWAY_W = 8.0
WINDOW_L = 5.0
WINDWAY_L = 20.0
LABIUM_T = 0.5
LABIUM_ANGLE = 18.0
HOLE_X = 12.0                     # finger hole grid on the front flat (+-x, +-z)
HOLE_Z = 7.0
PIN_D = 2.0
PIN_DEPTH = 4.5
PIN_ANGLES = (205, 270, 335)      # on the seam rim, back side
LANYARD_D = 3.0                   # 2 vertical holes through the seam rim (left/right)
PLATE_GAP = 8.0


def freq(i):
    return A4 * 2 ** (SEMIS[i] / 12)


def conductance(d):
    r = d / 2
    return math.pi * r * r / (WALL + END_CORR * r)


def diameter_for(k):
    # pi r^2 - END_CORR k r - k t = 0
    r = (END_CORR * k + math.sqrt((END_CORR * k) ** 2 + 4 * math.pi * k * WALL)) / (2 * math.pi)
    return 2 * r


def cents(i, ks):
    tot = 1 + sum(ks[HOLES.index(h)] for h in FINGERING[i])
    return 1200 * math.log2(math.sqrt(tot) * freq(0) / freq(i))


def fit_holes():
    """Minimax fit (cents) of the 4 relative conductances to the scale (pattern search)."""
    ks = [0.25, 0.4, 1.8, 0.55]
    worst = lambda k: max(abs(cents(i, k)) for i in range(1, len(NOTES)))
    step = 0.1
    while step > 1e-5:
        improved = False
        for j in range(4):
            for sgn in (1, -1):
                t = list(ks)
                t[j] *= 1 + sgn * step
                if worst(t) < worst(ks):
                    ks, improved = t, True
        if not improved:
            step /= 2
    return ks


def shape_factor():
    """V = 2 Rx Ry H * I, I = int_0^1 s^2 g(min(1, FLAT/s)) ds (cut ellipse area / ab)."""
    n, tot = 4000, 0.0
    for i in range(n):
        s = (i + 0.5) / n
        t = min(1.0, FLAT / s)
        g = math.pi - (math.acos(t) - t * math.sqrt(1 - t * t))
        tot += s * s * g / n
    return 2 * tot


A_W = WINDWAY_W * WINDOW_L
K_W = conductance(2 * math.sqrt(A_W / math.pi))
VOLUME = K_W * C_SOUND**2 / (2 * math.pi * freq(0)) ** 2
RX = (VOLUME / (ASPECT * SLOPE * shape_factor())) ** (1 / 3)
RY = ASPECT * RX
H = SLOPE * RX
Y_F = FLAT * RY
Y_E = Y_F + LABIUM_T / 2          # jet / edge line
Y_O = Y_F + WALL                  # outer front face
KS = fit_holes()
HOLE_DS = {h: diameter_for(k * K_W) for h, k in zip(HOLES, KS)}
HOLE_POS = {"LI": (-HOLE_X, HOLE_Z), "LM": (-HOLE_X, -HOLE_Z), "RI": (HOLE_X, HOLE_Z),
            "RM": (HOLE_X, -HOLE_Z)}


def tuning_table():
    rows = [f"C5 {freq(0):.2f}: V {VOLUME / 1000:.1f} cm3, K_w {K_W:.2f}, Rx {RX:.1f} Ry {RY:.1f} H {H:.1f}"]
    for i in range(1, len(NOTES)):
        rows.append(f"{NOTES[i]} {freq(i):.2f}: open {'+'.join(FINGERING[i])} -> {cents(i, KS):+.1f} c")
    rows += [f"hole {h}: k {k:.3f}, d {HOLE_DS[h]:.2f}" for h, k in zip(HOLES, KS)]
    return "\n".join(rows)


def _cone(rx, ry, h):
    c = Cone(rx, 0, h, align=(Align.CENTER, Align.CENTER, Align.MIN))
    c = scale(c, by=(1, ry / rx, 1))
    return c + mirror(c, about=Plane.XY)


def _yz_prism(pts, half_w):
    return extrude(Plane.YZ * Polygon(*pts, align=None), half_w, both=True)


def build_whole():
    big = 200
    rxo, ryo, ho = RX + RIM, RY + RIM, H + WALL * 1.6
    outer = _cone(rxo, ryo, ho) & Pos(0, Y_O - big / 2, 0) * Box(big, big, 2 * (ho - 6))
    cavity = _cone(RX, RY, H) & Pos(0, Y_F - big / 2, 0) * Box(big, big, big)

    # fipple heights: window top just under the chamber roof behind the windway
    y_w, y_r = Y_E - WINDWAY_H / 2, Y_E + WINDWAY_H / 2
    z_wt = H * (1 - y_w / RY) - 0.5
    z_lab = z_wt - WINDOW_L
    tip = z_wt + WINDWAY_L
    hw = WINDWAY_W / 2
    beak_back = y_w - 9.0
    beak = Pos(0, (beak_back + Y_O) / 2, tip / 2) * Box(WINDWAY_W + 6, Y_O - beak_back, tip)
    beak = fillet(beak.edges().filter_by(Axis.Z), 2.0)
    body = outer + beak - cavity

    run = (Y_O + 1 - (Y_F + LABIUM_T)) / math.tan(math.radians(LABIUM_ANGLE))
    airway = _yz_prism([(y_w, tip + 1), (y_w, z_lab), (Y_F + LABIUM_T, z_lab), (Y_O + 1, z_lab - run),
                        (Y_O + 1, z_wt + Y_O + 1 - y_r), (y_r, z_wt), (y_r, tip + 1)], hw)
    # mouthpiece tip: bevel the back so the lips close on a 3 mm thick end
    lip = _yz_prism([(y_w - 2.0, tip + 1), (y_w - 2.0, tip), (beak_back - 1, tip - 12), (beak_back - 1, tip + 1)],
                    WINDWAY_W)
    body = body - airway - lip

    for h, (x, z) in HOLE_POS.items():
        dp = (HOLE_DS[h] - HOLE_UNDERSIZE) / math.sqrt(1 + (1 - math.pi / 4) / math.pi)
        td = teardrop_hole(dp, 2 * WALL + 4, along="Y", tip="+Z" if z > 0 else "-Z")
        body -= Pos(x, Y_F + WALL / 2, z) * td
    ring = lambda deg: ((RX + RIM / 2) * math.cos(math.radians(deg)), (RY + RIM / 2) * math.sin(math.radians(deg)))
    for deg in PIN_ANGLES:
        x, y = ring(deg)
        body -= Pos(x, y, 0) * (pin_hole(PIN_D, PIN_DEPTH) + mirror(pin_hole(PIN_D, PIN_DEPTH), about=Plane.XY))
    for deg in (0, 180):          # lanyard: cord goes down through one rim hole and up the other
        x, y = ring(deg)
        body -= Pos(x, y, 0) * Cylinder(hole_d(LANYARD_D) / 2, 2 * H)
    return body


def build():
    whole = build_whole()
    top = split(whole, bisect_by=Plane.XY, keep=Keep.TOP)
    bot = split(whole, bisect_by=Plane.XY, keep=Keep.BOTTOM)
    bot = Rot(0, 180, 0) * bot                    # flip seam-down (x mirrored, y kept)
    dx = RX + RIM + PLATE_GAP / 2
    return [Pos(-dx, 0, 0) * top, Pos(dx, 0, 0) * bot]


