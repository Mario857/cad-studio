"""egg-shakers: set of 4 egg shakers (45 mm eggs) with press-fit halves, one fill each.

Spec
- Egg 45 mm long x 35 mm diameter (big-end half-ellipsoid 19.5 mm + small-end 25.5 mm).
- Split at the equator. Big-end half = male: 3 mm press-fit spigot (OD 31.0) below the seam
  with a 40 deg shoulder (leaves a 1.5 mm decorative V-groove at the seam). Small-end half = female:
  socket ID clearance(31.0, "press"), 3 mm deep, 40 deg chamfered top.
- Both halves print open side down (rim / spigot on the bed), no supports: the inner domes are
  capped by 40 deg cones, the socket roof is a 40 deg chamfer, outer domes shrink upwards.
- 8 halves on one plate (4 x 2 grid, male row y>0, female row y<0).

Acoustics / sound (computed below)
- The sound is particle impacts on the shell. Impact duration (Hertz contact, sphere on ABS wall)
    t_c = 2.87 (m^2 / (R E*^2 v))^(1/5),  1/E* = (1-nu1^2)/E1 + (1-nu2^2)/E2,  v = 1 m/s
  sets the spectral corner f_c ~ 1/t_c: short/hard/light contacts = bright, long/soft = dark.
  Number of grains sets density ("hiss" vs "rattle"); mass sets loudness.
- Closed cavity: first (dipole) air mode of a rigid sphere of equal volume, f = 2.0816 c / (2 pi a)
  (~8 kHz) gives a small presence peak common to all four.
- Fill: FILL_FRAC of the cavity volume x bulk density -> grams (weigh it on a kitchen scale).

TUNING (regenerated by `python model.py`; cavity 11.2 cm3, first air mode ~8.2 kHz)
  egg | fill (vol %)      | grams | grains | f_c wall / grain-grain | energy/hit | character
  1   | rice 30 %         |  2.8  |  ~170  | 35 / 43 kHz            |   8 uJ     | bright soft "chh", classic
  2   | red lentils 30 %  |  2.8  |  ~65   | 20 / 20 kHz            |  22 uJ     | darker, woody, chunkier
  3   | steel BB 4.5 15 % |  8.4  |  ~22   | 14 / 72 kHz            | 187 uJ     | loudest; dull wall thud +
      |                   |       |        |                        |            | very bright steel clicks
  4   | fine sand 15 %    |  2.7  | ~15000 | 190 / 640 kHz          |  0.1 uJ    | quiet smooth hiss, no attack
  Brightness rationale: shorter contact (light, hard, small grains) pushes energy up the spectrum;
  energy per hit sets loudness/attack; grain count sets texture (few = rattle, many = hiss).

Fine-tune after printing
- Start with the listed grams, shake, then add/remove ~10 %: more fill = louder but duller and
  less "chick"; < 5 % = clicky/thin. Sand: add slowly, too much kills the attack.
- When happy, glue the joint with a ring of CA/ABS cement (or leave press-fit to change fills).

Hardware: long-grain rice ~3 g, red lentils ~3 g, steel BBs 4.5 mm ~9 g (~22 pcs), dry fine sand
~3 g (sieved, oven-dried). Optional: CA glue or ABS cement.

Assembly: deburr the spigot; pour the fill into the small-end (female) half; press the big-end
spigot into the socket until the shoulder stops (vise or table, it is a press fit); glue if wanted.

Assumptions: egg dims typical of commercial egg shakers; impact speed 1 m/s; material constants:
ABS E 2.2 GPa nu .35; rice E 3 GPa; lentil E 1 GPa; steel 200 GPa; quartz sand 70 GPa (r 0.25 mm).
"""

import math

from build123d import *

from cadlib import *

META = dict(
    material="AzureFilm ABS PLUS @BBL H2C 0.4 nozzle",
    quality="standard",
    standing=False,
    loads=[],
    print_orientation=(0, 0, 0),  # laid out open side down already
    supports="off",
    brim="auto",
    # WARN accepted: 8 separate bodies = 4 eggs x 2 halves, printed together on purpose.
)

# --- Egg -------------------------------------------------------------------------------------
LENGTH = 45.0
R_EQ = 17.5                       # equator radius (35 mm egg)
BIG_A = 19.5                      # big-end half-ellipsoid height
SMALL_A = LENGTH - BIG_A          # small-end half height
WALL = 2.0
SPIGOT_H = 3.0
SPIGOT_OD = 31.0
SPIGOT_WALL = 1.5
SOCKET_D = clearance(SPIGOT_OD, "press")
POLE_FLAT = 0.6
TAN_ROOF = math.tan(math.radians(40))   # all inner roofs/shoulders 40 deg from vertical
CAV_R0 = SPIGOT_OD / 2 - SPIGOT_WALL   # cavity radius at the seam (14.0)
PITCH_X = 2 * R_EQ + 6
PITCH_Y = 2 * R_EQ + 6

# --- Fills: name, particle radius mm, density kg/m3, E GPa, nu, bulk g/cm3, fill fraction ---
C_SOUND = 343.0
E_ABS, NU_ABS = 2.2e9, 0.35
IMPACT_V = 1.0
FILLS = [
    ("rice", 1.4, 1450, 3.0, 0.3, 0.85, 0.30),
    ("red lentils", 2.0, 1300, 1.0, 0.3, 0.85, 0.30),
    ("steel BB 4.5", 2.25, 7850, 200.0, 0.29, 5.0, 0.15),
    ("fine sand", 0.25, 2650, 70.0, 0.17, 1.6, 0.15),
]


def _ell(z, a):
    return R_EQ * math.sqrt(max(0.0, 1 - (z / a) ** 2))


def _half_ellipsoid(r, a):
    """Upper half of an ellipsoid of revolution (equator radius r, height a) on z = 0."""
    e = scale(Sphere(r), by=(1, 1, a / r))
    top = a - POLE_FLAT                # tiny flat pole: no degenerate apex in the mesh
    return e & Pos(0, 0, top / 2) * Box(3 * r, 3 * r, top)


def _cavity(a):
    """Cavity of a half from its seam (z=0) up: seam-radius cylinder & wall offset & 40 deg cap."""
    h = a - WALL
    cyl = Cylinder(CAV_R0, h + 1, align=(Align.CENTER, Align.CENTER, Align.MIN))
    z_ap = max(h - 0.5, CAV_R0 / TAN_ROOF + 0.7)   # apex under the pole, roof >= CAV_R0 up to z 0.7
    rb = (z_ap + 2) * TAN_ROOF
    cap = Cone(rb, 1.0, (rb - 1.0) / TAN_ROOF, align=(Align.CENTER, Align.CENTER, Align.MIN))  # 2 mm flat
    return cyl & _half_ellipsoid(R_EQ - WALL, h) & Pos(0, 0, -2) * cap


def male():
    """Big-end half, spigot down (the shorter half: its 40 deg roof fits above r = CAV_R0)."""
    z0 = SPIGOT_H
    ro = SPIGOT_OD / 2
    spigot = Cylinder(ro, z0 + 0.5, align=(Align.CENTER, Align.CENTER, Align.MIN))
    spigot = chamfer(spigot.edges().group_by(Axis.Z)[0], 0.4)
    dome = _half_ellipsoid(R_EQ, BIG_A) & Cone(ro, ro + TAN_ROOF * BIG_A, BIG_A,
                                                 align=(Align.CENTER, Align.CENTER, Align.MIN))
    outer = spigot + Pos(0, 0, z0) * dome
    bore = Pos(0, 0, -1) * Cylinder(CAV_R0, z0 + 1.5, align=(Align.CENTER, Align.CENTER, Align.MIN))
    return outer - bore - Pos(0, 0, z0) * _cavity(BIG_A)


def female():
    """Small-end half, rim down, press-fit socket in the rim (taller: room for socket + roof)."""
    rs = SOCKET_D / 2
    outer = _half_ellipsoid(R_EQ, SMALL_A)
    outer = chamfer(outer.edges().group_by(Axis.Z)[0], 0.4)
    socket = Pos(0, 0, -1) * Cylinder(rs, SPIGOT_H + 1, align=(Align.CENTER, Align.CENTER, Align.MIN))
    roof = Pos(0, 0, SPIGOT_H) * Cone(rs, CAV_R0, (rs - CAV_R0) / TAN_ROOF, align=(Align.CENTER, Align.CENTER, Align.MIN))
    return outer - socket - roof - _cavity(SMALL_A)


def cavity_volume():
    """Assembled inner volume (mm3) of the two half cavities (seam radius continuous)."""
    return _cavity(BIG_A).volume + _cavity(SMALL_A).volume


def hertz_corner(r_mm, rho, e_gpa, nu, on_wall=True):
    """1 / Hertz contact time: grain on the ABS wall, or grain on grain (m, R halved)."""
    r = r_mm / 1000
    m = rho * 4 / 3 * math.pi * r**3
    e2, nu2 = (E_ABS, NU_ABS) if on_wall else (e_gpa * 1e9, nu)
    e_star = 1 / ((1 - nu**2) / (e_gpa * 1e9) + (1 - nu2**2) / e2)
    m_eff, r_eff = (m, r) if on_wall else (m / 2, r / 2)
    t_c = 2.87 * (m_eff**2 / (r_eff * e_star**2 * IMPACT_V)) ** 0.2
    return 1 / t_c, m


def tuning_table():
    v = cavity_volume()
    a_eq = (3 * v / (4 * math.pi)) ** (1 / 3) / 1000
    f_cav = 2.0816 * C_SOUND / (2 * math.pi * a_eq)
    rows = [f"cavity {v / 1000:.1f} cm3, first air mode {f_cav / 1000:.1f} kHz"]
    for i, (name, r, rho, e, nu, bulk, frac) in enumerate(FILLS, 1):
        fc, m = hertz_corner(r, rho, e, nu)
        fg, _ = hertz_corner(r, rho, e, nu, on_wall=False)
        grams = frac * v / 1000 * bulk
        rows.append(f"egg {i} {name}: {frac:.0%} vol, {grams:.1f} g, ~{grams / (m * 1000):.0f} grains, "
                    f"f_c wall {fc / 1000:.0f} kHz, grain-grain {fg / 1000:.0f} kHz, "
                    f"impact {0.5 * m * IMPACT_V**2 * 1e6:.1f} uJ")
    return "\n".join(rows)


def build():
    parts = []
    for i in range(len(FILLS)):
        x = (i - (len(FILLS) - 1) / 2) * PITCH_X
        parts.append(Pos(x, PITCH_Y / 2, 0) * male())
        parts.append(Pos(x, -PITCH_Y / 2, 0) * female())
    return parts


if __name__ == "__main__":
    print(tuning_table())
